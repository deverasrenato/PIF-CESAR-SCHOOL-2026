/* =========================================================================
 * Desenho da Letra "R" no Console
 * -------------------------------------------------------------------------
 * Este programa utiliza um único printf e sequências de escape '\n' para 
 * desenhar a letra "R" estilizada em formato de bloco no console.
 * ========================================================================= */

#include <stdio.h>

int main() {
    printf("RRRR \n");
    printf("R   R\n");
    printf("RRRR \n");
    printf("R  R \n");
    printf("R   R\n");

    return 0; // Finaliza o programa com sucesso
}
